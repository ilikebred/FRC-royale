// Package the supplied MP3 bytes for file:// playback, where fetch is blocked.
const fs=require('node:fs'),path=require('node:path');
const names=['frc-start-sound','frc-end','frc-resume','frc-warning'];
const clips=Object.fromEntries(names.map(name=>[name,fs.readFileSync(path.join(__dirname,'sounds',name+'.mp3')).toString('base64')]));
fs.writeFileSync(path.join(__dirname,'sounds','field-clips.js'),'// Generated by build-sounds.cjs from the supplied MP3s.\nconst FIELD_CLIPS='+JSON.stringify(clips)+';\n');
